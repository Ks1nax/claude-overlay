def default_system_prompt():
    return SYSTEM_PROMPT.replace(
        "{FORMULA_RULES}", FORMULA_RULES_LATEX if S.math_render else FORMULA_RULES_PLAIN
    ).replace("{STYLE_RULES}", STYLE_RULES_STUDENT if S.student_style else "")


def default_listen_prompt():
    return LISTEN_DETAILED if S.listen_style == "detailed" else LISTEN_PROMPT


def system_prompt():
    return (S.prompt_system or "").strip() or default_system_prompt()


def listen_prompt():
    return (S.prompt_listen or "").strip() or default_listen_prompt()


def analyze_prompt():
    return (S.prompt_analyze or "").strip() or ANALYZE_PROMPT
